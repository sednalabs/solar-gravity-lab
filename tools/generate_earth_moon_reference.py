#!/usr/bin/env python3
"""Compile the checked-in Horizons responses into the native laboratory seed.

No network is used by the build. Raw responses and exact query parameters live
under data/earth-moon-lab so their frame, epoch and origin remain inspectable.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/earth-moon-lab"
OUTPUT = ROOT / "engine/data/src/earth_moon_lab.rs"
BODIES = (
    ("sun", "10", "Star", 132712440041.93938, 696340.0),
    ("earth", "399", "Planet", 398600.435436, 6371.01),
    ("moon", "301", "Moon", 4902.800066, 1737.4),
)
EXPECTED_EPOCHS = (2451545.0, 2451546.0, 2451552.0, 2451575.0)


def load_reference():
    states = {}
    digests = []
    for name, target, _, _, _ in BODIES:
        raw = (DATA / f"{name}-horizons.json").read_bytes()
        query = json.loads((DATA / f"{name}-query.json").read_text())
        digest = hashlib.sha256(raw).hexdigest()
        recorded_digest = query["response_sha256"]
        if not isinstance(recorded_digest, str) or not recorded_digest.startswith("sha256:"):
            raise ValueError(f"{name}: response digest must use the sha256: identifier prefix")
        if recorded_digest.removeprefix("sha256:") != digest:
            raise ValueError(f"{name}: response digest does not match recorded query")
        params = query["parameters"]
        expected = {
            "COMMAND": target, "CENTER": "500@0", "REF_PLANE": "FRAME",
            "REF_SYSTEM": "ICRF", "VEC_CORR": "NONE", "OUT_UNITS": "KM-S",
            "TIME_TYPE": "TDB", "VEC_TABLE": "2",
        }
        for key, value in expected.items():
            if params[key].strip("'") != value:
                raise ValueError(f"{name}: unexpected {key}")
        response = json.loads(raw)
        if response.get("signature", {}).get("source") != "NASA/JPL Horizons API":
            raise ValueError(f"{name}: unexpected API signature")
        text = response["result"]
        if "{source: DE441}" not in text or "Reference frame : ICRF" not in text:
            raise ValueError(f"{name}: unexpected source or reference frame")
        rows = []
        for line in text.split("$$SOE\n", 1)[1].split("$$EOE", 1)[0].splitlines():
            fields = [field.strip() for field in line.split(",")]
            if len(fields) != 9:
                raise ValueError(f"{name}: unexpected vector row")
            values = [float(value) for value in fields[2:8]]
            if not all(math.isfinite(value) for value in values):
                raise ValueError(f"{name}: non-finite vector")
            rows.append((float(fields[0]), [value * 1000.0 for value in values]))
        if tuple(epoch for epoch, _ in rows) != EXPECTED_EPOCHS:
            raise ValueError(f"{name}: unexpected epochs")
        states[name] = rows
        digests.append(f"{name}:{digest}\n")
    dataset_digest = hashlib.sha256("".join(digests).encode()).hexdigest()
    return states, dataset_digest


def vector(values):
    return "[" + ", ".join(repr(value) for value in values) + "]"


def render_module():
    states, digest = load_reference()
    lines = [
        "// Generated by tools/generate_earth_moon_reference.py; do not hand-edit vectors.",
        "// Geometric DE441 states, ICRF, solar-system barycentre, SI units.",
        "// Dynamics after the initial epoch are our Newtonian three-body model.",
        "use crate::CanonicalBodySpec;",
        "use solarlab_domain::{BodyClass, Vector3d};", "",
        'pub const EARTH_MOON_LAB_ID: &str = "lab.earth-moon";',
        'pub const EARTH_MOON_LAB_DATASET_ID: &str = "jpl-horizons-de441-j2000-sun-earth-moon-v1";',
        f'pub const EARTH_MOON_LAB_DIGEST: &str = "sha256:{digest}";',
        "pub const EARTH_MOON_LAB_EPOCH_JD_TDB: f64 = 2_451_545.0;",
        "pub const EARTH_MOON_LAB_MAX_SUBSTEP_SECONDS: f64 = 60.0;", "",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct EarthMoonReferenceEpoch {",
        "    pub elapsed_seconds: f64,",
        "    /// Sun, Earth, Moon, in that order.",
        "    pub positions_m: [[f64; 3]; 3],",
        "    pub velocities_mps: [[f64; 3]; 3],",
        "}", "",
        "pub const EARTH_MOON_REFERENCE_EPOCHS: [EarthMoonReferenceEpoch; 4] = [",
    ]
    for index, epoch in enumerate(EXPECTED_EPOCHS):
        lines.extend([
            "    EarthMoonReferenceEpoch {",
            f"        elapsed_seconds: {(epoch - EXPECTED_EPOCHS[0]) * 86400.0:.1f},",
            "        positions_m: [",
            *[f"            {vector(states[name][index][1][:3])}," for name, *_ in BODIES],
            "        ],", "        velocities_mps: [",
            *[f"            {vector(states[name][index][1][3:])}," for name, *_ in BODIES],
            "        ],", "    },",
        ])
    lines.extend([
        "];", "", "#[must_use]",
        "pub fn earth_moon_lab_bodies() -> Vec<CanonicalBodySpec> {",
        "    // Horizons physical-summary GM values are divided by the solver's G.",
        "    // This preserves the intended gravitational parameters without mass rounding.",
        "    const G: f64 = 6.67430e-11;",
        "    let metadata = [",
        *[f'        ("{name}", BodyClass::{kind}, {gm!r} * 1.0e9 / G, {radius * 1000.0!r}),' for name, _, kind, gm, radius in BODIES],
        "    ];",
        "    metadata.into_iter().enumerate().map(|(index, (body_id, body_class, mass_kg, radius_m))| {",
        "        let p = EARTH_MOON_REFERENCE_EPOCHS[0].positions_m[index];",
        "        let v = EARTH_MOON_REFERENCE_EPOCHS[0].velocities_mps[index];",
        "        CanonicalBodySpec {",
        "            body_id: body_id.into(), body_class, mass_kg, radius_m,",
        "            position_m: Vector3d { x: p[0], y: p[1], z: p[2] },",
        "            velocity_mps: Vector3d { x: v[0], y: v[1], z: v[2] },",
        "        }",
        "    }).collect()", "}", "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render_module()
    if args.check:
        # Ignore rustfmt whitespace while still checking every data token.
        def compact(value):
            tokens = "".join(value.split())
            for closer in "])}":
                tokens = tokens.replace("," + closer, closer)
            return tokens
        if compact(OUTPUT.read_text()) != compact(generated):
            raise SystemExit("Earth–Moon reference module differs from recorded source data")
        print("Earth–Moon source digests, frame, units, epochs and generated vectors verified")
    else:
        OUTPUT.write_text(generated)
        print(OUTPUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
